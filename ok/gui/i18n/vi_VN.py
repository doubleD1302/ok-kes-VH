class VietnameseTranslator(QTranslator):
    def __init__(self, parent=None):
        super().__init__(parent)
        self.translations = VIETNAMESE_QT_TRANSLATIONS

    def translate(self, context, sourceText, disambiguation=None, n=-1):
        if not sourceText:
            return ""
        # 1. Exact context match
        ctx = self.translations.get(context)
        if ctx and sourceText in ctx:
            return ctx[sourceText]
        # 2. Default fallback
        default_ctx = self.translations.get("@default")
        if default_ctx and sourceText in default_ctx:
            return default_ctx[sourceText]
        # 3. Fallback search across all known contexts
        for c, mapping in self.translations.items():
            if c != "@default" and sourceText in mapping:
                return mapping[sourceText]
        return ""


def install_vietnamese_translator(app, locale=None):
    translator = VietnameseTranslator(app)
    app.installTranslator(translator)
    QCoreApplication.installTranslator(translator)
    return translator
